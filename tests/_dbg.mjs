import { chromium } from "playwright";
const b = await chromium.launch({ headless:false, channel:"chrome" });
const p = await b.newPage({ viewport:{width:1200,height:900} });
p.on("pageerror", e=>console.log("pageerror", e.message.slice(0,400)));
p.on("console", m=>{ if(m.type()==="error") console.log("console", m.text().slice(0,400)); });
p.on("requestfailed", r=>console.log("reqfail", r.url().slice(0,150)));
await p.goto("http://127.0.0.1:5191");
await p.waitForTimeout(25000);
console.log((await p.locator("body").innerText()).slice(0,300));
await p.screenshot({ path: "D:/Claude/virtugenium-night/frames/dbg.png" });
await b.close();
